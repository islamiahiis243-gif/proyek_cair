-- Keep privileged RFIN and company-verification implementations outside PostgREST's public schema.
create schema if not exists private;
revoke all on schema private from public,anon;
grant usage on schema private to authenticated;
alter function public.issue_rfin_a(uuid,text,interval) set schema private;
alter function public.issue_rfin_b(uuid,text,interval) set schema private;
alter function public.redeem_rfin(text) set schema private;
alter function public.revoke_rfin(uuid) set schema private;
alter function public.review_company_registration(uuid,text,text) set schema private;
revoke all on function private.issue_rfin_a(uuid,text,interval) from public,anon;
revoke all on function private.issue_rfin_b(uuid,text,interval) from public,anon;
revoke all on function private.redeem_rfin(text) from public,anon;
revoke all on function private.revoke_rfin(uuid) from public,anon;
revoke all on function private.review_company_registration(uuid,text,text) from public,anon;
grant execute on function private.issue_rfin_a(uuid,text,interval) to authenticated;
grant execute on function private.issue_rfin_b(uuid,text,interval) to authenticated;
grant execute on function private.redeem_rfin(text) to authenticated;
grant execute on function private.revoke_rfin(uuid) to authenticated;
grant execute on function private.review_company_registration(uuid,text,text) to authenticated;
create or replace function public.issue_rfin_a(p_company_id uuid,p_recipient_email text,p_expires_in interval default interval '7 days') returns text language sql security invoker set search_path='' as $$ select private.issue_rfin_a(p_company_id,p_recipient_email,p_expires_in); $$;
create or replace function public.issue_rfin_b(p_company_id uuid,p_recipient_email text,p_expires_in interval default interval '7 days') returns text language sql security invoker set search_path='' as $$ select private.issue_rfin_b(p_company_id,p_recipient_email,p_expires_in); $$;
create or replace function public.redeem_rfin(p_code text) returns jsonb language sql security invoker set search_path='' as $$ select private.redeem_rfin(p_code); $$;
create or replace function public.revoke_rfin(p_token_id uuid) returns void language sql security invoker set search_path='' as $$ select private.revoke_rfin(p_token_id); $$;
create or replace function public.review_company_registration(p_request_id uuid,p_decision text,p_review_notes text default null) returns uuid language sql security invoker set search_path='' as $$ select private.review_company_registration(p_request_id,p_decision,p_review_notes); $$;
revoke all on function public.issue_rfin_a(uuid,text,interval) from public,anon;
revoke all on function public.issue_rfin_b(uuid,text,interval) from public,anon;
revoke all on function public.redeem_rfin(text) from public,anon;
revoke all on function public.revoke_rfin(uuid) from public,anon;
revoke all on function public.review_company_registration(uuid,text,text) from public,anon;
grant execute on function public.issue_rfin_a(uuid,text,interval) to authenticated;
grant execute on function public.issue_rfin_b(uuid,text,interval) to authenticated;
grant execute on function public.redeem_rfin(text) to authenticated;
grant execute on function public.revoke_rfin(uuid) to authenticated;
grant execute on function public.review_company_registration(uuid,text,text) to authenticated;
drop policy if exists rfin_attempts_explicit_deny on public.rfin_redemption_attempts;
create policy rfin_attempts_explicit_deny on public.rfin_redemption_attempts for all to anon,authenticated using(false) with check(false);
